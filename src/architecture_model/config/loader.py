# Functional block auto-discovery
# ---------------------------------------------------------------------------


def _discover_functional_blocks(root: Path) -> list[FunctionalBlockConfig]:
    """Auto-discover functional blocks from source directory structure.

    Strategy:
    1. Find the "source root" — the package directory with Python modules.
    2. Each immediate subdirectory with .py files becomes an F-block.
    3. Names are derived from directory name and module docstrings.
    4. Files in the source root itself (not in subdirs) become a "Core" block.

    Falls back to top-level directory analysis if no clear package structure.
    """
    # Step 1: Find the source root (deepest package with subpackages)
    source_root = _find_source_root(root)
    if source_root is None:
        # No clear package structure — try top-level dirs
        return _fblocks_from_top_level_dirs(root)

    # Step 2: Enumerate subdirectories that contain Python code
    subdirs = _get_code_subdirectories(source_root)
    if not subdirs:
        return []

    # Step 3: Generate F-blocks from subdirectories
    blocks: list[FunctionalBlockConfig] = []
    rel_source = source_root.relative_to(root)

    for idx, subdir in enumerate(sorted(subdirs), start=1):
        block_id = f"F{idx}"
        rel_dir = str(subdir.relative_to(root))

        # Collect .py files in this subdir (non-recursive for files list)
        py_files = sorted(
            str(f.relative_to(root)) for f in subdir.rglob("*.py") if f.name != "__init__.py"
        )

        # Derive name from directory name
        dir_name = subdir.name.replace("_", " ").replace("-", " ").title()

        # Try to get description from __init__.py docstring
        description = _get_package_description(subdir)

        # Auto-discover sub-blocks from sub-directories
        sub_blocks = _discover_sub_blocks(subdir, block_id, root)

        blocks.append(
            FunctionalBlockConfig(
                id=block_id,
                name=dir_name,
                dirs=[rel_dir],
                files=py_files,
                description_source=description or f"auto-discovered from {rel_dir}/",
                sub_blocks=sub_blocks,
            )
        )

    return blocks


def _find_source_root(root: Path) -> Path | None:
    """Find the main source package directory.

    Checks common patterns:
    - src/<package>/  (src-layout)
    - <package>/  (flat layout, where <package> has __init__.py)
    - lib/<package>/
    """
    # src-layout: src/<something>/__init__.py with subdirectories
    src_dir = root / "src"
    if src_dir.is_dir():
        for child in src_dir.iterdir():
            if child.is_dir() and (child / "__init__.py").exists():
                # Check it has subdirectories with code
                if _get_code_subdirectories(child):
                    return child

    # Flat layout: look for a package dir at root level
    # (exclude common non-package dirs)
    _skip = {
        "tests",
        "test",
        "docs",
        "doc",
        "scripts",
        "bin",
        "output",
        "build",
        "dist",
        ".git",
        ".venv",
        "venv",
        "node_modules",
        "__pycache__",
        ".eggs",
        ".tox",
        "htmlcov",
        ".mypy_cache",
    }
    for child in sorted(root.iterdir()):
        if child.is_dir() and child.name not in _skip and not child.name.startswith("."):
            if (child / "__init__.py").exists() and _get_code_subdirectories(child):
                return child

    # lib-layout
    lib_dir = root / "lib"
    if lib_dir.is_dir():
        for child in lib_dir.iterdir():
            if child.is_dir() and (child / "__init__.py").exists():
                if _get_code_subdirectories(child):
                    return child

    return None


def _get_code_subdirectories(package_dir: Path) -> list[Path]:
    """Get immediate subdirectories that contain Python code (are subpackages)."""
    result = []
    for child in sorted(package_dir.iterdir()):
        if not child.is_dir() or child.name.startswith("_") or child.name.startswith("."):
            continue
        # Must have at least one .py file (directly or nested)
        py_files = list(child.rglob("*.py"))
        if py_files:
            result.append(child)
    return result


def _get_package_description(package_dir: Path) -> str:
    """Extract a short description from a package's __init__.py docstring."""
    init_file = package_dir / "__init__.py"
    if not init_file.exists():
        return ""

    content = init_file.read_text(encoding="utf-8", errors="ignore")
    # Simple docstring extraction (first triple-quoted string)
    for quote in ('"""', "'''"):
        if quote in content:
            start = content.index(quote) + 3
            end = content.find(quote, start)
            if end > start:
                doc = content[start:end].strip()
                # Return first line only
                first_line = doc.split("\n")[0].strip()
                if first_line:
                    return first_line
    return ""


def _fblocks_from_top_level_dirs(root: Path) -> list[FunctionalBlockConfig]:
    """Fallback: create F-blocks from top-level directories with Python files.

    Used when no clear package structure (src/ or flat package) is found.
    """
    _skip = {
        "tests",
        "test",
        "docs",
        "doc",
        "output",
        "build",
        "dist",
        ".git",
        ".venv",
        "venv",
        "node_modules",
        "__pycache__",
        ".eggs",
        ".tox",
        "htmlcov",
        ".mypy_cache",
        "alembic",
    }

    blocks: list[FunctionalBlockConfig] = []
    idx = 1

    for child in sorted(root.iterdir()):
        if not child.is_dir() or child.name in _skip or child.name.startswith("."):
            continue

        py_files = sorted(
            str(f.relative_to(root)) for f in child.rglob("*.py") if f.name != "__init__.py"
        )
        if not py_files:
            continue

        dir_name = child.name.replace("_", " ").replace("-", " ").title()
        description = _get_package_description(child) if (child / "__init__.py").exists() else ""

        # Auto-discover sub-blocks from sub-directories
        sub_blocks = _discover_sub_blocks(child, f"F{idx}", root)

        blocks.append(
            FunctionalBlockConfig(
                id=f"F{idx}",
                name=dir_name,
                dirs=[child.name],
                files=py_files,
                description_source=description or f"auto-discovered from {child.name}/",
                sub_blocks=sub_blocks,
            )
        )
        idx += 1

    return blocks


def _derive_layers_from_blocks(blocks: list[FunctionalBlockConfig]) -> list[LayerConfig]:
    """Derive layers from F-block directories when no heuristic layers found.

    Groups blocks into generic layers based on directory naming patterns.
    """
    layers: list[LayerConfig] = []
    all_dirs = [d for b in blocks for d in b.dirs]

    # For simple packages, create one layer per F-block dir
    for d in all_dirs:
        layer_id = d.split("/")[-1] + "-layer"
        layers.append(LayerConfig(id=layer_id, dirs=[d]))

    return layers
