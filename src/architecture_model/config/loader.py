"""Configuration loader for the Architecture Model Standard.

Loads project configuration from .architecture-model.yaml or auto-discovers
project structure when no config file exists. Includes full auto-generation
of functional blocks from directory structure and import analysis.
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

import yaml

from .schema import (
    ProjectConfig,
    OutputConfig,
    LayerConfig,
    FunctionalBlockConfig,
    MetricConfig,
)


CONFIG_FILENAME = ".architecture-model.yaml"


def load_config(root: Path) -> ProjectConfig:
    """Load project configuration from .architecture-model.yaml.

    Args:
        root: Project root directory containing the config file.

    Returns:
        ProjectConfig loaded from file.

    Raises:
        FileNotFoundError: If config file doesn't exist.
    """
    config_path = root / CONFIG_FILENAME
    if not config_path.exists():
        raise FileNotFoundError(
            f"No {CONFIG_FILENAME} found in {root}. "
            f"Run `architecture-model init` to generate one, or use get_config() for auto-discovery."
        )

    data = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    if not data:
        data = {}

    return ProjectConfig.from_dict(data, root=root)


def discover_config(root: Path) -> ProjectConfig:
    """Auto-discover project configuration by scanning filesystem.

    Inspects the directory structure to infer layers, functional blocks,
    and metrics without requiring a config file. Produces a complete,
    usable configuration including auto-generated F-blocks.

    Args:
        root: Project root directory to scan.

    Returns:
        ProjectConfig with auto-discovered values.
    """
    name = root.name

    # Discover layers from common directory patterns
    layers = _discover_layers(root)

    # Discover metrics from what directories exist
    metrics = _discover_metrics(root)

    # Auto-discover functional blocks from source structure
    functional_blocks = _discover_functional_blocks(root)

    # If no layers found from heuristics but we found F-blocks,
    # derive layers from the F-block directories
    if not layers and functional_blocks:
        layers = _derive_layers_from_blocks(functional_blocks)

    return ProjectConfig(
        name=name,
        system=name,
        output=OutputConfig(),
        layers=layers,
        functional_blocks=functional_blocks,
        metrics=metrics,
        root=root,
    )


def get_config(root: Path) -> ProjectConfig:
    """Load config from file if it exists, otherwise auto-discover.

    This is the recommended entry point — it always returns a valid config.
    When loading from YAML, auto-discovers sub_blocks for any block that
    doesn't already define them.

    Args:
        root: Project root directory.

    Returns:
        ProjectConfig (from file or auto-discovered).
    """
    config_path = root / CONFIG_FILENAME
    if config_path.exists():
        config = load_config(root)
        # Auto-discover sub_blocks for blocks that don't define them in YAML
        for block in config.functional_blocks:
            if not block.sub_blocks and block.dirs:
                block_path = root / block.dirs[0]
                if block_path.is_dir():
                    block.sub_blocks = _discover_sub_blocks(block_path, block.id, root)
        return config
    return discover_config(root)


def write_config(config: ProjectConfig, root: Path | None = None) -> Path:
    """Write a ProjectConfig to .architecture-model.yaml.

    Args:
        config: The configuration to write.
        root: Directory to write to. Defaults to config.root.

    Returns:
        Path to the written config file.
    """
    if root is None:
        root = config.root

    config_path = root / CONFIG_FILENAME
    data = config.to_dict()

    # Add auto-generation marker
    header = (
        "# Architecture Model Standard - Project Descriptor\n"
        "# Auto-generated by: architecture-model init\n"
        "# Edit freely - subsequent 'init' runs will not overwrite manual changes.\n\n"
    )

    yaml_content = yaml.dump(data, default_flow_style=False, sort_keys=False, allow_unicode=True)
    config_path.write_text(header + yaml_content, encoding="utf-8")
    return config_path


# ---------------------------------------------------------------------------
# Auto-discovery heuristics
# ---------------------------------------------------------------------------

# Common layer patterns for Python web projects
_LAYER_HEURISTICS: list[tuple[str, list[str]]] = [
    ("web-layer", ["app/routers", "app/views", "app/api", "src/api", "api/"]),
    ("services-layer", ["app/services", "src/services", "services/"]),
    ("data-layer", ["app/models", "src/models", "models/", "alembic"]),
    ("pipeline-layer", ["scripts", "pipeline", "src/pipeline", "jobs/"]),
    ("scheduling-layer", ["app/tasks", "tasks/", "celery/"]),
]

# Common metric patterns
_METRIC_HEURISTICS: list[dict[str, Any]] = [
    {
        "label": "router",
        "paths": ["app/routers", "app/api", "src/api"],
        "pattern": "*.py",
        "exclude": ["__init__.py"],
    },
    {
        "label": "model",
        "paths": ["app/models", "src/models"],
        "pattern": "*.py",
        "exclude": ["__init__.py", "base.py"],
    },
    {
        "label": "migration",
        "paths": ["alembic/versions", "migrations"],
        "pattern": "*.py",
        "exclude": [],
    },
    {
        "label": "template",
        "paths": ["app/templates", "templates"],
        "pattern": "**/*.html",
        "exclude": [],
        "recursive": True,
    },
]


def _discover_layers(root: Path) -> list[LayerConfig]:
    """Discover architecture layers from directory structure."""
    layers: list[LayerConfig] = []

    for layer_id, candidate_dirs in _LAYER_HEURISTICS:
        found_dirs = [d for d in candidate_dirs if (root / d).is_dir()]
        if found_dirs:
            layers.append(LayerConfig(id=layer_id, dirs=found_dirs))

    return layers


def _discover_metrics(root: Path) -> list[MetricConfig]:
    """Discover countable metrics from directory structure."""
    metrics: list[MetricConfig] = []

    for heuristic in _METRIC_HEURISTICS:
        for path in heuristic["paths"]:
            if (root / path).is_dir():
                metrics.append(
                    MetricConfig(
                        label=heuristic["label"],
                        path=path,
                        pattern=heuristic["pattern"],
                        exclude=heuristic["exclude"],
                        recursive=heuristic.get("recursive", False),
                    )
                )
                break  # Use first match per label

    return metrics


# ---------------------------------------------------------------------------
# Sub-block auto-discovery
# ---------------------------------------------------------------------------


def _discover_sub_blocks(
    block_dir: Path,
    block_id: str,
    root: Path,
    depth: int = 0,
    max_depth: int = 3,
) -> list:
    """Discover sub-blocks from sub-directories within a block's directory.

    Only creates sub-blocks for directories that contain .py files.
    Recurses up to max_depth levels.
    """
    from .schema import SubBlockConfig

    if depth >= max_depth:
        return []

    sub_blocks = []
    sub_idx = 0

    try:
        children = sorted(block_dir.iterdir())
    except (PermissionError, OSError):
        return []

    for child in children:
        if not child.is_dir():
            continue
        if child.name.startswith(".") or child.name == "__pycache__":
            continue

        # Check if this directory has Python files
        py_files = list(child.glob("*.py"))
        if not py_files:
            continue

        sub_idx += 1
        # Use letter suffixes: F8.A, F8.B, etc. For deeper levels: F8.A.1, F8.A.2
        if depth == 0:
            sub_id = f"{block_id}.{chr(64 + sub_idx)}"  # A, B, C...
        else:
            sub_id = f"{block_id}.{sub_idx}"  # numeric for deeper levels

        # Get name from directory or __init__.py docstring
        name = child.name.replace("_", " ").title()
        init_file = child / "__init__.py"
        if init_file.exists():
            try:
                content = init_file.read_text(encoding="utf-8")
                # Extract module docstring
                import ast

                tree = ast.parse(content)
                if (
                    tree.body
                    and isinstance(tree.body[0], ast.Expr)
                    and isinstance(tree.body[0].value, ast.Constant)
                ):
                    docstring = tree.body[0].value.value
                    first_line = docstring.strip().split("\n")[0].strip()
                    if first_line and len(first_line) < 80:
                        name = first_line
            except Exception:
                pass

        rel_dir = str(child.relative_to(root))

        # Recurse into sub-directories
        nested = _discover_sub_blocks(child, sub_id, root, depth + 1, max_depth)

        sub_blocks.append(
            SubBlockConfig(
                id=sub_id,
                name=name,
                dirs=[rel_dir],
                files=[],
                description="",
                sub_blocks=nested,
            )
        )

    return sub_blocks


